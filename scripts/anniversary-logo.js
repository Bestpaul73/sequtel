// ============================================================================
// anniversary-logo.js
// Автоматическая смена юбилейного логотипа на главной странице Sequtel
// ============================================================================

// Ждём полной загрузки HTML-документа.
document.addEventListener("DOMContentLoaded", function () {

    // ------------------------------------------------------------------------
    // Находим изображение юбилейного логотипа.
    // Если его нет на странице — просто завершаем работу скрипта.
    // ------------------------------------------------------------------------
    const logo = document.querySelector(".anniversary-logo");

    if (!logo) {
        return;
    }

    // ------------------------------------------------------------------------
    // Массив всех вариантов логотипов.
    // Чтобы добавить новый вариант, достаточно добавить ещё одну строку.
    // ------------------------------------------------------------------------
    const logos = [
        "./images/SEQUTEL_Anniversary_logo_01.png",
        "./images/SEQUTEL_Anniversary_logo_02.png",
        "./images/SEQUTEL_Anniversary_logo_03.png",
        "./images/SEQUTEL_Anniversary_logo_04.png"
    ];

    // ------------------------------------------------------------------------
    // Предзагружаем все изображения.
    // Благодаря этому при переключении не будет задержек.
    // ------------------------------------------------------------------------
    logos.forEach(function (src) {

        // Создаём временный объект изображения.
        const image = new Image();

        // Загружаем картинку в кэш браузера.
        image.src = src;

    });

    // ------------------------------------------------------------------------
    // Индекс текущего логотипа.
    // Начинаем с первого изображения.
    // ------------------------------------------------------------------------
    let currentIndex = 0;

    // ------------------------------------------------------------------------
    // Интервал между переключениями (в миллисекундах).
    // 3000 = 3 секунды.
    // ------------------------------------------------------------------------
    const changeInterval = 1000*60*60*24;

    // ------------------------------------------------------------------------
    // Длительность анимации исчезновения/появления.
    // Должна быть меньше интервала переключения.
    // ------------------------------------------------------------------------
    const fadeDuration = 300;

    // ------------------------------------------------------------------------
    // Запускаем таймер.
    // ------------------------------------------------------------------------
    setInterval(function () {

        // ------------------------------------------------------------
        // Делаем логотип прозрачным.
        // ------------------------------------------------------------
        logo.style.opacity = "0";

        // ------------------------------------------------------------
        // Ждём окончания анимации исчезновения.
        // ------------------------------------------------------------
        setTimeout(function () {

            // --------------------------------------------------------
            // Переходим к следующему логотипу.
            // --------------------------------------------------------
            currentIndex++;

            // --------------------------------------------------------
            // Если дошли до конца массива —
            // возвращаемся к первому изображению.
            // --------------------------------------------------------
            if (currentIndex >= logos.length) {
                currentIndex = 0;
            }

            // --------------------------------------------------------
            // Меняем картинку.
            // --------------------------------------------------------
            logo.src = logos[currentIndex];

            // --------------------------------------------------------
            // Возвращаем непрозрачность.
            // --------------------------------------------------------
            logo.style.opacity = "1";

        }, fadeDuration);

    }, changeInterval);

});